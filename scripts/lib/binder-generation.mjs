import { escapeHtml } from './content-rendering.mjs';

export const TABLE_OF_CONTENTS_CODE = 'TABLE_OF_CONTENTS';
export const BINDER_CODE = 'EMERGENCY_PREPAREDNESS_BINDER';

function orderedDocuments(documents) {
  return [...documents].sort((a, b) =>
    a.meta.sectionNumber - b.meta.sectionNumber || a.meta.code.localeCompare(b.meta.code)
  );
}

export function generateTableOfContentsPages(documents) {
  let binderPage = 2;
  const rows = orderedDocuments(documents).map(({ meta }) => {
    const firstPage = binderPage;
    const lastPage = binderPage + meta.pageCount - 1;
    binderPage = lastPage + 1;
    const pages = firstPage === lastPage ? firstPage : `${firstPage}–${lastPage}`;
    return `<tr><td>${escapeHtml(meta.code)}</td><td>${escapeHtml(meta.title)}</td>`
      + `<td>${escapeHtml(meta.section)}</td><td class="toc-pages">${pages}</td></tr>`;
  }).join('');

  return `<article class="sheet front toc-sheet" aria-label="Table of contents">
  <main class="content">
    <div class="kicker"><span>Emergency Preparedness Binder</span><span>Contents</span></div>
    <h1>Table of contents</h1>
    <p class="lede">All handouts produced by this build, in binder order.</p>
    <table class="toc-table">
      <thead><tr><th scope="col">Code</th><th scope="col">Document</th><th scope="col">Section</th><th scope="col">Binder page</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>
    <footer class="footer"><span>Generated by npm run build</span><span>1 of 1</span><span>${documents.length} documents</span></footer>
  </main>
</article>`;
}

export function generateTableOfContentsHtml(template, documents) {
  return template
    .replace('{{title}}', 'Emergency Preparedness Binder — Table of Contents')
    .replace('{{cssPath}}', '../assets/print.css')
    .replace('{{pages}}', generateTableOfContentsPages(documents));
}

export function generateBinderHtml(template, documents, handoutHtml) {
  const handoutPages = orderedDocuments(documents).map(({ meta }) => {
    const html = handoutHtml.get(meta.code);
    const body = html?.match(/<body>([\s\S]*)<\/body>/)?.[1];
    if (!body) throw Error(`${meta.code}: generated HTML has no body to add to the binder`);
    return body;
  }).join('');
  return template
    .replace('{{title}}', 'Emergency Preparedness Binder')
    .replace('{{cssPath}}', '../assets/print.css')
    .replace('{{pages}}', generateTableOfContentsPages(documents) + handoutPages);
}
