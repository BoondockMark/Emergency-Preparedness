import { escapeHtml } from './content-rendering.mjs';
import { SECTIONS } from './metadata.mjs';

export function generateBinderIndex(documents) {
  const groups = SECTIONS.map((section, index) => {
    const rows = documents
      .filter(document => document.meta.section === section)
      .sort((a, b) => a.meta.code.localeCompare(b.meta.code))
      .map(({ meta }) => {
        const { code, title, status, version, lastReviewed, pageCount } = meta;
        return `| ${code} | ${title} | ${status} | ${version} | ${lastReviewed} | ${pageCount} |`;
      })
      .join('\n');
    return `## ${index + 1}. ${section}\n\n| Code | Title | Status | Version | Last reviewed | Pages |\n|---|---|---|---|---|---:|\n${rows || '| — | _No handouts yet_ | — | — | — | — |'}`;
  });
  return `# Binder index\n\nGenerated by \`npm run build\`. Only approved documents may be published to Moodle.\n\n${groups.join('\n\n')}\n`;
}

export function generateMoodleIndex(documents) {
  const approved = documents.filter(document => document.meta.status === 'approved');
  const sections = SECTIONS.map(section => {
    const entries = approved
      .filter(document => document.meta.section === section)
      .sort((a, b) => a.meta.code.localeCompare(b.meta.code));
    const contents = entries.length
      ? `<ul>${entries.map(({ meta }) => `<li><a href="PDF_URL/${meta.code}.pdf">${escapeHtml(meta.title)}</a> (${meta.code}, reviewed ${meta.lastReviewed})</li>`).join('')}</ul>`
      : '<p><em>No approved handouts currently published.</em></p>';
    return `<section><h2>${escapeHtml(section)}</h2>${contents}</section>`;
  }).join('');
  return `<!-- Generated; approved handouts only. Replace PDF_URL after Moodle upload. -->\n<div class="lhhfw-binder"><h1>Emergency Preparedness Binder</h1>${sections}</div>\n`;
}
